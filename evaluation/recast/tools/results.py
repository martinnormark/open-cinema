"""Render evaluation/recast/results.md from reviewer scores and run evidence.

Usage: python3 results.py

Scores: evaluation/recast/scores.json (A1–A5, A1w, B1–B8, gates, notes per run).
Evidence: artifacts/evaluation/recast/runs/<pipeline>/<clip>/summary.json and router.json.
Gates G1/G2/G4 are also derived from the scores and G3 from container durations,
so a reviewer cannot pass a run the measurements fail. Unscored runs that failed
to return a clip are logged as G5.
"""

from __future__ import annotations

import json
from statistics import mean, median

import recast

OUT = recast.HERE / "results.md"
RUNS = recast.ART / "runs"

# Published Router rates in USD per second of delivered video (docs: comfy-router pricing).
RATES = {
    "kling-o1": 0.168,
    "kling-v3-omni": 0.168,
    "wan27-edit": 0.10,
    "wan27-edit-keyframe": 0.10,
    "happyhorse-edit": 0.14,
    "aleph2-keyframe": 0.40,
    "aleph2-text": 0.40,
    "genjutsu": 0.97,
}
KEYFRAME_USD = 0.06  # one FLUX 3 1K edit for the first-frame guide


def _json(path):
    return json.loads(path.read_text()) if path.exists() else {}


def seconds(text: str | None) -> float | None:
    # "1920x1080@24.00 121f 5.04s"
    try:
        return float(text.split()[-1].rstrip("s"))
    except (AttributeError, IndexError, ValueError):
        return None


def cost(pipeline: str, summary: dict) -> float | None:
    rate = RATES.get(pipeline)
    secs = seconds(summary.get("result")) or seconds(summary.get("source"))
    if rate is None or secs is None:
        return None
    extra = KEYFRAME_USD if "keyframe" in pipeline else 0
    return round(rate * secs + extra, 2)


def gates_for(s: dict, summary: dict) -> list[str]:
    a, b = s["A"], s["B"]
    gates = set(s.get("gates", []))
    if a[0] == 0:
        gates.add("G1")
    if b[0] <= 1:
        gates.add("G2")
    if b[7] <= 1:
        gates.add("G4")
    src, res = seconds(summary.get("source")), seconds(summary.get("result"))
    fps = summary.get("source", "").split("@")[-1].split()[0] if summary.get("source") else None
    if src and res and fps and abs(src - res) > 1 / float(fps) + 1e-3:
        gates.add("G3")
    return sorted(gates)


def main() -> None:
    scores = _json(recast.HERE / "scores.json")
    rows, passed = [], []
    for key, s in sorted(scores["runs"].items()):
        pipeline, clip = key.split("/")
        d = RUNS / pipeline / clip
        summary = _json(d / "summary.json")
        a, b = s["A"], s["B"]
        gates = gates_for(s, summary)
        change, pres = mean(a), mean(b)
        ok = not gates
        if ok:
            passed.append((change, pres, min(b), a[0]))
        usd = cost(pipeline, summary)
        rows.append([
            clip.split("-")[0], pipeline, f"{a[0]}/{s.get('A1w', '–')}", *map(str, a[1:]), f"{change:.2f}",
            *map(str, b), f"{pres:.2f} (min {min(b)})", ", ".join(gates) or "pass",
            f"{usd:.2f}" if usd is not None else "–", str(round(summary.get("turnaround_s") or 0)) or "–",
            str(summary.get("protected_psnr_median", "–")), str(summary.get("ref_sim", "–")),
            str(summary.get("protected_face_sim", "–")), s["notes"],
        ])
    scored = set(scores["runs"])
    for err in sorted(RUNS.glob("*/*/error.txt")):
        key = f"{err.parent.parent.name}/{err.parent.name}"
        if key in scored or (err.parent / "result.mp4").exists():
            continue
        last = err.read_text().strip().splitlines()[-1][:200].replace("|", "/")
        rows.append([err.parent.name.split("-")[0], err.parent.parent.name, *["–"] * 6, *["–"] * 9, "G5", "0.00", "–", "–", "–", "–",
                     f"No clip returned: {last}"])
    head = ["Clip", "Pipeline", "A1/A1w", "A2", "A3", "A4", "A5", "Change", "B1", "B2", "B3", "B4", "B5", "B6", "B7", "B8",
            "Preservation", "Gates", "Cost (USD)", "Turnaround (s)", "pPSNR", "ref_sim", "prot_face", "Notes"]
    lines = [
        "# Character recast results log",
        "",
        "Scored with the shared [rubric](../rubric.md) and the [recast addendum](README.md); generated by `tools/results.py` from "
        "[scores.json](scores.json) and the run evidence in `artifacts/evaluation/recast/runs/<pipeline>/<clip>/` (ignored): "
        "`side-by-side.mp4`, `contact-sheet.jpg`, `metrics.json`, `identity.json`, `router.json`.",
        "",
        f"Reviewer: {scores['reviewer']}. Cost is the published Router rate times the delivered clip length (the keyframe pipeline adds one FLUX 3 edit). "
        "Turnaround is wall time from submission to result, **including the shared Router queue**, which every overnight thread was using and which dominated every run. "
        "pPSNR is the median protected-region PSNR (dB) against the source outside the dilated target matte; generative edits re-render the whole frame, so read it next to the review. "
        "ref_sim is the median ArcFace similarity of the recast face to the Character; prot_face is the median similarity of every other face to its source.",
        "",
        "| " + " | ".join(head) + " |",
        "| " + " | ".join("---" for _ in head) + " |",
        *("| " + " | ".join(r) + " |" for r in rows),
        "",
    ]
    if passed:
        lines.append(
            f"{len(passed)} of {len(scores['runs'])} scored runs pass every gate; on passing runs the median Change is "
            f"{median(p[0] for p in passed):.2f} and the median Preservation is {median(p[1] for p in passed):.2f}."
        )
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(OUT)


if __name__ == "__main__":
    main()
