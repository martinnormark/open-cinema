#!/usr/bin/env python3
"""Render evaluation/background/results.md from reviewer scores and run evidence.

  results_table.py

Scores: evaluation/background/scores.json (A1–A5, B1–B8, gates, notes per run).
Evidence: artifacts/evaluation/background/runs/<run>/router-log.json and review/metrics.json.
Gates G1/G2/G4 are also derived from the scores, and G3 from container durations,
so a reviewer cannot pass a run the measurements fail.
"""
import json
import os
from statistics import mean

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ART = os.path.join(ROOT, "artifacts", "evaluation", "background", "runs")
OUT = os.path.join(ROOT, "evaluation", "background", "results.md")


def cost(pipeline, metrics, log):
    """USD from published rates and the delivered clip (see scores.json `cost_usd`)."""
    src = (metrics or {}).get("source") or {}
    res = (metrics or {}).get("result") or {}
    seconds = res.get("duration") or src.get("duration") or 0
    frames = src.get("frames") or 0
    p = pipeline.split("+")[0]
    if p == "bria-composite":
        return 0.05 * seconds
    if p == "switchx-ref":
        return 0.143 * -(-frames // 30)
    if p in ("kling-o1-edit", "comfyui-kling"):
        units = None
        try:
            units = float(log["result"]["data"]["final_unit_deduction"])
        except (KeyError, TypeError, ValueError):
            pass
        return 0.14 * (units if units is not None else 0.9 * seconds)
    if p == "wan27-edit":
        return 0.10 * seconds
    if p == "aleph2-edit":
        return 0.40 * seconds
    if p == "bfl-video-edit":
        return 0.0429 * seconds
    return None


def main():
    scores = json.load(open(os.path.join(ROOT, "evaluation", "background", "scores.json")))
    rows = []
    for run, s in sorted(scores["runs"].items()):
        clip, pipeline = run.split("-", 1)
        d = os.path.join(ART, run)
        log = json.load(open(os.path.join(d, "router-log.json"))) if os.path.exists(os.path.join(d, "router-log.json")) else {}
        mpath = os.path.join(d, "review", "metrics.json")
        metrics = json.load(open(mpath)) if os.path.exists(mpath) else {}
        a, b = s["A"], s["B"]
        gates = set(s.get("gates", []))
        if a[0] == 0:
            gates.add("G1")
        if b[0] <= 1:
            gates.add("G2")
        if b[2] <= 1:
            gates.add("G3")
        if b[7] <= 1:
            gates.add("G4")
        src_fps = (metrics.get("source") or {}).get("fps") or 25
        if metrics and abs(metrics.get("duration_delta_s", 0)) > 1 / src_fps + 1e-3:
            gates.add("G3")
        c = cost(pipeline, metrics, log)
        if "+lock" in pipeline:
            base = os.path.join(ART, run.replace("+lock", ""), "router-log.json")
            log = json.load(open(base)) if os.path.exists(base) else log
        elapsed = log.get("elapsed_s")
        pp = metrics.get("protected_psnr_median")
        rows.append(
            "| "
            + " | ".join(
                [
                    run,
                    clip.upper(),
                    pipeline,
                    *map(str, a),
                    f"{mean(a):.2f}",
                    *map(str, b),
                    f"{mean(b):.2f} (min {min(b)})",
                    ", ".join(sorted(gates)) or "pass",
                    f"{c:.2f}" if c is not None else "–",
                    f"{elapsed:.0f}" if elapsed else "–",
                    f"{pp:.1f}" if pp else "–",
                    s["notes"],
                ]
            )
            + " |"
        )
    head = [
        "# Background replacement results log",
        "",
        "Scored with the shared [rubric](../rubric.md); generated by `evaluation/scripts/results_table.py` from [scores.json](scores.json) and the run evidence. One row per clip × pipeline run. Evidence for each run is in `artifacts/evaluation/background/runs/<run>/` (ignored): `side-by-side.mp4`, `contact-sheet.jpg`, `metrics.json`, `router-log.json`.",
        "",
        f"Reviewer: {scores['reviewer']}. Cost is computed from published Router rates and the delivered clip; `+lock` rows show the generative run's cost; the matte adds the cost of the matting run (SwitchX here, or about $0.05/s with Bria remove-background), which can run in parallel. Turnaround is wall time from submission to downloaded result, **including the shared Router queue**, which dominated every run on this night. pPSNR is the median protected-region PSNR in dB against the source (higher means less change to the foreground).",
        "",
        "| Run | Clip | Pipeline | A1 | A2 | A3 | A4 | A5 | Change | B1 | B2 | B3 | B4 | B5 | B6 | B7 | B8 | Preservation | Gates | Cost (USD) | Turnaround (s) | pPSNR | Notes |",
        "| --- | ---- | -------- | -- | -- | -- | -- | -- | ------ | -- | -- | -- | -- | -- | -- | -- | -- | ------------ | ----- | ---------- | -------------- | ----- | ----- |",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(head + rows) + "\n")
    print(f"{len(rows)} rows -> {OUT}")


if __name__ == "__main__":
    main()
